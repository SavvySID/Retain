"""Load a trusted local model and explain predictions in honest model-output units."""

import hashlib
import json
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
import shap

from churn.schema import FEATURE_NAMES, validate_customer


def build_explainer(bundle: dict[str, Any]) -> Any:
    """Use training-only background rows and the model's supported exact SHAP explainer."""
    estimator = bundle["pipeline"].named_steps["model"]
    background = bundle["background"]
    if bundle["explanation_units"] == "log-odds":
        return shap.LinearExplainer(estimator, shap.maskers.Independent(background, max_samples=len(background)))
    return shap.TreeExplainer(
        estimator, data=background, feature_perturbation="interventional", model_output="probability"
    )


def explain_matrix(bundle: dict[str, Any], explainer: Any, frame: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    """Return signed SHAP values grouped to original fields and one baseline per row."""
    transformed = bundle["pipeline"].named_steps["preprocess"].transform(frame[FEATURE_NAMES])
    explanation = explainer(transformed)
    values = np.asarray(explanation.values)
    bases = np.asarray(explanation.base_values)
    if values.ndim == 3:
        values = values[:, :, 1]
        bases = bases[:, 1]
    bases = np.broadcast_to(bases.reshape(-1), (len(frame),))
    grouped = np.column_stack([
        values[:, np.asarray(bundle["transformed_groups"]) == name].sum(axis=1) for name in FEATURE_NAMES
    ])
    return grouped, bases


def retention_suggestions(record: dict[str, Any]) -> list[str]:
    """Offer clearly rule-based discussion prompts, never inferred causal interventions."""
    suggestions = []
    if record["Contract"] == "Month-to-month":
        suggestions.append("Discuss whether a longer-term plan fits this customer's preferences; no uplift is estimated.")
    if record["InternetService"] != "No" and record["TechSupport"] == "No":
        suggestions.append("Ask whether technical-support access or unresolved service issues need attention.")
    if record["tenure"] <= 12:
        suggestions.append("Review onboarding and ask about the early service experience.")
    if record["PaymentMethod"] == "Electronic check":
        suggestions.append("Ask about billing friction and preferred payment options; do not assume the payment method causes churn.")
    return suggestions or ["Review the customer's service experience before deciding on any retention action."]


class ChurnService:
    """Serve the frozen selected model; uploads are never used for training."""

    def __init__(self, root: Path) -> None:
        """Load only integrity-checked artifacts generated by this project's training command."""
        artifact_dir = root / "artifacts"
        manifest = json.loads((artifact_dir / "manifest.json").read_text(encoding="utf-8"))
        for filename, digest in manifest["sha256"].items():
            path = artifact_dir / filename
            if path.parent != artifact_dir or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
                raise ValueError(f"Artifact integrity check failed: {filename}. Retrain with scripts/train.py.")
        self.summary = json.loads((artifact_dir / "summary.json").read_text(encoding="utf-8"))
        self.customers = json.loads((artifact_dir / "customers.json").read_text(encoding="utf-8"))
        # Only project-generated local files are loaded: pickle/joblib is unsafe for untrusted models.
        self.bundle = joblib.load(artifact_dir / "model.joblib")
        self.explainer = build_explainer(self.bundle)

    def predict(self, record: dict[str, Any], explain: bool = True) -> dict[str, Any]:
        """Predict a validated scenario and optionally reconcile all SHAP contributions."""
        valid = validate_customer(record)
        frame = pd.DataFrame([valid], columns=FEATURE_NAMES)
        probability = float(self.bundle["pipeline"].predict_proba(frame)[0, 1])
        threshold = float(self.bundle["threshold"])
        result: dict[str, Any] = {
            "probability": probability, "prediction": probability >= threshold,
            "risk_level": "High" if probability >= threshold else "Low", "threshold": threshold,
            "model_name": self.bundle["model_name"],
        }
        if explain:
            grouped, bases = explain_matrix(self.bundle, self.explainer, frame)
            units = self.bundle["explanation_units"]
            output = float(self.bundle["pipeline"].decision_function(frame)[0]) if units == "log-odds" else probability
            reconstructed = float(bases[0] + grouped[0].sum())
            error = abs(reconstructed - output)
            if not np.isfinite(error) or error > 1e-5:
                raise ArithmeticError(f"SHAP additivity check failed ({error}); no explanation returned.")
            reconstructed_probability = float(1 / (1 + np.exp(-reconstructed))) if units == "log-odds" else reconstructed
            result["explanation"] = {
                "base_value": float(bases[0]), "output_value": output, "units": units,
                "contributions": sorted([
                    {"feature": name, "value": valid[name], "contribution": float(grouped[0, i])}
                    for i, name in enumerate(FEATURE_NAMES)
                ], key=lambda item: abs(item["contribution"]), reverse=True),
                "reconstructed_probability": reconstructed_probability, "additivity_error": error,
            }
            result["suggestions"] = retention_suggestions(valid)
        return result
